"""Build the current Odyssey sea maze; legacy modules remain reproducible."""
import argparse
import hashlib
import json
from pathlib import Path

from h3m import mapfile, paths
from h3m.world import Assets
from odyssey.well_journey import generate
from odyssey.guidance import STOPS


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--output',type=Path,default=Path('out/Odyssey-Homecoming-Labyrinth.h3m'))
    parser.add_argument('--seed',type=int,default=20260905)
    args=parser.parse_args()
    files=[f for f in paths.iter_maps() if not f.name.startswith(('Odyssey-','Forge-'))]
    assets=Assets.cached(files,paths.out_dir()/'world-assets.json')
    m,r=generate(assets,args.seed)
    args.output.parent.mkdir(parents=True,exist_ok=True)
    mapfile.save(args.output,m)
    r['file_sha256']=hashlib.sha256(args.output.read_bytes()).hexdigest()
    args.output.with_suffix('.report.json').write_text(json.dumps(r,ensure_ascii=False,indent=2),encoding='utf-8')
    guide=['# '+r['name'],'','Редакция 12. HotA 1.8.0, 72×72, два уровня, одиночный сценарий. Пять сложностей: 80–200%.',
        'Старое сохранение не получает исправления карты.','',
        '## Начало','',
        'Отбейте троянский дозор и садитесь в корабль. Дальше двигайтесь по проливам. '
        'Если проход закрыт, в текущей бухте осталось основное испытание. '
        'Боковые гроты с наградой необязательны; из них возвращаются тем же путём. '
        'Не снимайте шляпу адмирала.','',
        '## Изменения','',
        '- Большинство боёв открывает путь. Редкие трофеи остаются у особых противников; золота за бои нет.',
        '- Глаз циклопа защищает от ослепления; испытайте его против единорогов. Позднее можно выбрать один из двух обменов.',
        '- Эол даёт Меч адского пламени (+6 к нападению) перед зелёными драконами. Меч остаётся у вас до финала.',
        '- На острове ложной Итаки усмирите ветры на суше. Уцелевшие моряки укрылись в хижине. Возвращаться к Эолу не требуется.',
        '- Первые две морские засады усилены втрое; после сирен — 5 древних чудищ. В проливе — 200 сирен.',
        '- На Трое есть мастерская боевых машин. В охраняемом обозе — 2250 золотых на баллисту и палатку; доход ждать не нужно.',
        '- На острове сирен можно пройти испытание Чаши тишины: экспертная Мудрость и разовые +30 маны.',
        '- У Сциллы и Харибды выберите аспидов или гидр. Оба прохода возвращаются на основную линию.',
        '- На острове перед развилкой можно отбить магический колодец у 30 воров и 15 кочевников. После боя колодец доступен для повторных посещений.',
        '- Стартовый отряд: 8 алебардщиков, 6 арбалетчиков и 2 мечника. Новых спутников нужно освобождать в боях.',
        '- У Полифема можно отбить Воскрешение. Продвинутая магия земли уже изучена; автоматического пополнения маны на стоянках нет.',
        '- За последнюю засаду даётся архангел. Второго можно получить в необязательном испытании феаков.',
        '- Финал — победа над усиленным Антиноем. В замке растут стрелки; дополнительные волны приходят на 15, 29 и 43-й день. Фактический найм зависит от ИИ.',
        '- У Антиноя нет Воскрешения; нападение/защита/сила магии/знания — 12/12/5/4.',
        '- Общего обзора больше нет. Туман открывается обычным исследованием.',
        f'- Всего {r["total_battles"]} столкновения, включая необязательные; {r["sea_battles"]} на море.','',
        '## Местные задачи — спойлеры','']
    for key,task in r['objectives'].items():guide.extend(['### '+STOPS[key][0],'',task,''])
    guide.extend(['## Проверки','',
        f'Проверено {r["landings"]["checked"]} высадок. Максимальный морской перегон: {r["pacing"]["max_steps"]} клеток. '
        f'До действия от пляжа: максимум {r["shore_access"]["max_steps"]} шагов.',
        'Двоичный формат, доступ к заданиям, расход припасов и отсутствие обходов проверены автоматически. '
        'Бои в модели считаются выигранными без потерь; полный игровой прогон и длительность ещё не измерены.',''])
    args.output.with_suffix('.md').write_text('\n'.join(guide),encoding='utf-8')
    print(f'{args.output.resolve()}\n{r["file_sha256"]}\n{r["objects"]} objects; {r["total_battles"]} encounters')


if __name__=='__main__':main()
