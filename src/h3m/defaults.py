"""Значения по умолчанию, извлечённые из карт самой игры.

Ни одно число здесь не придумано. Все получены статистикой по 221 карте из
поставки: берётся то значение, которое встречается чаще всего.

Причина такого подхода — дорого доставшийся урок. Первая сгенерированная карта
роняла редактор, и виноваты были ровно «разумные» значения, выбранные из общих
соображений: разрешить всё содержимое и залить рельеф видом тайла номер ноль.
В настоящих картах не бывает ни того, ни другого.

Мораль: там, где формат допускает значение, а игра его никогда не использует,
это значение почти наверняка нерабочее.
"""

from __future__ import annotations

from h3m.terrain import Terrain

#: Разрешённые герои: 20 байт, бит = разрешён.
#: Встречается на 28 картах SoD из 56 — самая частая маска.
#: Часть героев запрещена самой игрой: разрешить всех 156 нельзя.
ALLOWED_HEROES_SOD = bytes.fromhex("efffffffffffffffffffffffffffffffffff0100")

#: Запрещённые артефакты: 18 байт, бит = ЗАПРЕЩЁН (маска читается с инверсией).
#: Встречается на 24 картах SoD из 56. Запрещено 17 артефактов —
#: пустая маска, то есть «разрешено всё», в поставке не встречается вовсе.
BANNED_ARTIFACTS_SOD = bytes.fromhex("00000000000000000000000000000080ffff")

#: Запрещённые заклинания: 9 байт, бит = запрещён. Обычно ничего.
BANNED_SPELLS_SOD = bytes(9)

#: Запрещённые вторичные навыки: 4 байта, бит = запрещён. Обычно ничего.
BANNED_SKILLS_SOD = bytes(4)

#: Поведение ИИ: на 262 записях игроков из 265 стоит 0.
DEFAULT_AI_TACTIC = 0

#: Огрызок записи игрока, за которого нельзя играть (SoD — 13 байт).
#:
#: Выглядит как выравнивание, но выравниванием не является. Байт №7 равен
#: 0xFF во **всех 183** огрызках по всем 56 картам SoD из поставки — без
#: единого исключения. По раскладке полной записи на этом месте лежит
#: стартовый герой, а 0xFF там означает «героя нет». Ноль означал бы «герой
#: номер 0», то есть ссылку на героя у несуществующего игрока.
#:
#: Именно из-за нулей на этом месте редактор вылетал на первой карте,
#: собранной с нуля. В остальных позициях у настоящих карт встречается мусор
#: от предыдущих правок — он безразличен, а этот байт нет.
UNPLAYABLE_PLAYER_STUB_SOD = bytes.fromhex("00 00 00 00 00 00 00 ff 00 00 00 00 00")

#: Виды тайлов «заливки» для каждого типа рельефа.
#:
#: У каждого рельефа есть набор видов, которыми покрывают сплошные области, и
#: отдельные виды для переходов к соседнему рельефу. Здесь только заливка:
#: значения, встречающиеся в реальных картах чаще всего. Взять произвольный
#: допустимый номер нельзя — получится либо мусор на экране, либо падение.
PLAIN_VIEWS: dict[int, tuple[int, ...]] = {
    Terrain.DIRT: (21, 22, 23, 24, 25, 26, 27, 28),
    Terrain.SAND: (0, 1, 2, 3, 4, 5, 6, 7),
    Terrain.GRASS: (49, 50, 51, 52, 53, 54, 55, 56),
    Terrain.SNOW: (49, 50, 51, 52, 53, 54, 55, 56),
    Terrain.SWAMP: (49, 50, 51, 52, 53, 54, 55, 56),
    Terrain.ROUGH: (49, 50, 51, 52, 53, 54, 55, 56),
    Terrain.SUBTERRANEAN: (49, 50, 51, 52, 53, 54, 55, 56),
    Terrain.LAVA: (49, 50, 51, 52, 53, 54, 55, 56),
    Terrain.WATER: (22, 23, 24, 25, 26, 28, 29, 30),
    Terrain.ROCK: (0, 1, 2, 3, 4, 5, 6, 7),
    Terrain.HIGHLANDS: (78, 82, 84, 85, 88, 91, 92, 95),
    Terrain.WASTELAND: (77, 78, 79, 86, 89, 91, 92, 93),
}


def plain_views(terrain: int) -> tuple[int, ...]:
    """Виды тайлов для сплошной заливки данным рельефом."""
    views = PLAIN_VIEWS.get(terrain)
    if not views:
        raise ValueError(f"неизвестный тип рельефа: {terrain}")
    return views
