def episode(key: str) -> Episode:
    """Найти эпизод по ключу."""
    for item in ROUTE:
        if item.key == key:
            return item
    raise KeyError(f"нет эпизода {key!r}")


def validate() -> list[str]:
    """Проверить дизайн на внутреннюю согласованность.

    Дешёвая проверка до всякой генерации: опечатка в ключе или эпизод за
    границами карты обнаружатся здесь, а не после сборки файла.
    """
    problems: list[str] = []
    keys = [item.key for item in ROUTE]

    duplicates = {key for key in keys if keys.count(key) > 1}
    if duplicates:
        problems.append(f"повторяющиеся ключи: {sorted(duplicates)}")

    for item in ROUTE:
        x, y, z = item.anchor
        if not (0 <= x < MAP_SIZE and 0 <= y < MAP_SIZE):
            problems.append(f"{item.key}: опора ({x}, {y}) вне карты")
        if z not in (0, 1) or (z == 1 and not UNDERGROUND):
            problems.append(f"{item.key}: недопустимый слой {z}")
        if item.requires and item.requires not in keys:
            problems.append(f"{item.key}: требует несуществующий {item.requires!r}")

        if z == 1 and item.entrance is None:
            problems.append(f"{item.key}: эпизод под землёй, а вход не задан")
        if item.entrance is not None:
            ex, ey, ez = item.entrance
            if ez != 0:
                problems.append(f"{item.key}: вход должен быть на поверхности")
            if not (0 <= ex < MAP_SIZE and 0 <= ey < MAP_SIZE):
                problems.append(f"{item.key}: вход ({ex}, {ey}) вне карты")

    for index, item in enumerate(ROUTE):
        if not item.requires:
            continue
        if keys.index(item.requires) > index:
            problems.append(
                f"{item.key}: требует {item.requires!r}, который идёт позже по маршруту"
            )

    starts = [item for item in ROUTE if item.kind is Kind.START]
    if len(starts) != 1:
        problems.append(f"стартовых эпизодов должно быть ровно один, а не {len(starts)}")

    finales = [item for item in ROUTE if item.kind is Kind.FINALE]
    if len(finales) != 1:
        problems.append(f"финалов должно быть ровно один, а не {len(finales)}")

    problems += _validate_ambushes(keys)
    return problems


def _validate_ambushes(keys: list[str]) -> list[str]:
    """Засады: уникальность, границы и главное — что они идут после причины."""
    problems: list[str] = []
    seen: set[str] = set()
    cause = keys.index("polyphemus")

    for ambush in POSEIDON_AMBUSHES:
        if ambush.key in seen:
            problems.append(f"засада {ambush.key!r} повторяется")
        seen.add(ambush.key)

        x, y, z = ambush.position
        if not (0 <= x < MAP_SIZE and 0 <= y < MAP_SIZE):
            problems.append(f"засада {ambush.key}: позиция ({x}, {y}) вне карты")
        if z != 0:
            problems.append(f"засада {ambush.key}: засады только на поверхности")

        for neighbour in ambush.between:
            if neighbour not in keys:
                problems.append(
                    f"засада {ambush.key}: неизвестный эпизод {neighbour!r}"
                )
                continue
            if keys.index(neighbour) < cause:
                problems.append(
                    f"засада {ambush.key} стоит до пещеры Полифема — "
                    "гнев Посейдона не может опережать свою причину"
                )

    signed = [a for a in POSEIDON_AMBUSHES if a.sign]
    if len(signed) != 1:
        problems.append(
            f"объяснение засад должно звучать ровно один раз, а не {len(signed)}"
        )

    return problems
