"""Дизайн карты по мотивам «Одиссеи».

Документ и данные одновременно: то, что здесь описано, генератор потом читает
напрямую, без переписывания в другой формат.

## Замысел

Карта 36x36 — странствие по кругу. Одиссей выходит из Трои в левом нижнем углу
и обходит мир против часовой стрелки: вдоль южного берега на восток, вверх по
восточному краю, обратно на запад по северу, вниз по западному краю. Итака
лежит **в центре карты**, и попасть в неё можно только замкнув круг.

Такая планировка выбрана не ради красоты. У неё три полезных свойства:

* дом виден почти отовсюду и всю дорогу недостижим — это и есть сюжет поэмы;
* маршрут линеен, эпизоды не перепутать местами, сложность растёт ровно;
* центр остаётся под финал, а не тратится на проходной эпизод.

Подземелье — царство мёртвых. Вход один, в западной части круга.

## Тексты

Все реплики написаны заново. Переводы поэмы на русский — самостоятельные
литературные произведения, и брать из них строки в чужой проект неправильно;
к тому же язык игровых табличек короче и суше, чем гекзаметр.

Регистр выбран простой и слегка архаичный, без стилизации под перевод.

## Что осознанно не сделано

* **Кораблей нет.** Море по сюжету напрашивается, но плавание требует верфей,
  лодок и водного рельефа со своими правилами стыковки. Вместо этого эпизоды
  разделены узкими перешейками и стражами — структура странствия сохраняется,
  риск нет.
* **Ветвления нет.** Формат позволяет запирать проходы, но не даёт настоящего
  выбора с последствиями. Где в поэме выбор, там на карте цена: пройти можно
  всегда, но за плату.
* **Спутники не моделируются.** Потеря людей выражена потерей войск в боях,
  а не отдельной механикой.
"""

