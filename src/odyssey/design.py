@dataclass(slots=True)
class Ambush:
    """Засада Посейдона на перешейке между эпизодами.

    Засады отличаются от эпизодов тем, что не являются местами: их не
    посещают, на них натыкаются. Поэтому они стоят на узких проходах, а не
    в стороне от дороги, и обойти их нельзя.
    """

    key: str
    position: tuple[int, int, int]
    between: tuple[str, str]
    """Между какими эпизодами стоит — для читателя дизайна."""

    strength: str
    """Сила отряда словами, относительно текущих возможностей игрока."""

    sign: str = ""
    """Табличка перед засадой. У первой есть, у остальных нет — см. идею."""

    creatures: str = ""
    """Кто именно. Словами: конкретные существа выбираются при сборке."""


#: Гнев Посейдона.
#:
#: Идея, ради которой это стоит делать: в поэме преследование Посейдона —
#: **следствие** ослепления Полифема, а не отдельная напасть. На карте это
#: выражается буквально: до пещеры моря нет, после пещеры оно есть везде.
#: Игрок сам навлекает на себя то, что будет мешать ему до конца.
#:
#: Табличка стоит только у первой засады, и это намеренно. Первая объясняет
#: причину; дальше объяснение не нужно — оно уже прозвучало, и молчаливое
#: повторение работает лучше. Игрок сам достраивает связь.
#:
#: Сила растёт, но не догоняет игрока полностью: засады должны быть
#: неприятны, а не смертельны. Смертельна пещера, а это её эхо.
#:
#: **Про состав засад.** Морской бестиарий Посейдона — океаниды, никсы,
#: айссиды, морские змеи — целиком принадлежит HotA. Измерено по поставке:
