def course(source, target=None):
    target = target or NEXT[source]
    title, landmark = STOPS[target]
    return f'КУРС: {DIRECTIONS[source, target]}.\n{title}: {landmark}. Вход к пристани — с ЮГА, снизу острова.'


def briefing(key):
    result = f'ВЫ ЗДЕСЬ: {STOPS[key][0]}\n\nСЕЙЧАС: {TASKS[key]}'
    if key in NEXT:
        label = 'ПОСЛЕ ПЕРВОГО РАЗГОВОРА' if key == 'aeolus' else 'ПОСЛЕ ЗАВЕРШЕНИЯ'
        result += f'\n\n{label}\n{course(key)}'
    return result


